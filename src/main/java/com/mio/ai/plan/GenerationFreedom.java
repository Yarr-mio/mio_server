package com.mio.ai.plan;

/**
 * 생성 자유도 — 문장을 누가 얼마나 만드는가 (이슈 #303, 로드맵 §5.3).
 *
 * <p>전달 정책은 위험도 하나가 아니라 자유도와 함께 결정돼야 한다. 서버가 문구를 고정한
 * 응답과 모델이 자유롭게 쓴 응답을 같은 강도로 검사하면, 안전한 응답은 불필요하게 느리고
 * 위험한 응답은 충분히 검사되지 않는다.
 */
public enum GenerationFreedom {
    /** 서버가 문구를 고정한다. 모델 호출 없음. */
    TEMPLATE_ONLY,
    /** 정해진 틀에 값만 채운다. */
    SLOT_FILLING,
    /** 모델이 생성하되 계약(질문 수·문장 수·금지 표현)을 지켜야 한다. */
    CONSTRAINED,
    /** 계약 없는 자유 생성. 현재 계획되지 않은 턴이 여기 해당한다. */
    OPEN
}
