package com.mio.ai.security;

/**
 * {@link SecurityLevel#ATTACK} 으로 판정된 입력의 성격.
 *
 * <p>{@code ATTACK} 하나로 성격이 다른 두 입력을 함께 나르던 구조를 분리한다 (이슈 #260).
 * 등급({@code SecurityLevel})이 "얼마나 위험한가"라면 이 값은 "무엇을 시도하는가"이며,
 * 두 축은 독립이다. 따라서 판정원이 늘어 등급 병합이 생기더라도(이슈 #262) 이 값은
 * 등급 비교와 섞이지 않는다.
 */
public enum AttackKind {

    /** ATTACK 이 아닌 입력. */
    NONE,

    /**
     * 시스템 프롬프트 유출·지침 무시 등 모델 조작 시도.
     * 거절이 정답이며 대화를 이어갈 이유가 없다.
     */
    MANIPULATION,

    /**
     * 자해·자살 수단을 묻는 질의.
     *
     * <p>조작 의도일 수도 있지만 실제 위기 상태의 사용자가 그대로 입력할 수 있는 문장이고,
     * 입력만으로 둘을 구분할 수 없다. 오분류 비용이 비대칭이므로(조작을 위기로 처리하면
     * 불필요한 핫라인 노출에 그치지만, 위기를 조작으로 처리하면 도움이 필요한 사용자에게
     * 거절 메시지를 보내고 아무 기록도 남기지 않는다) 위기 쪽으로 처리한다.
     */
    SELF_HARM_INQUIRY
}
