package com.mio.ai.judge;

/**
 * 발화에 등장한 위기 어휘가 <b>누구의, 언제 상태</b>를 가리키는지 (이슈 #297).
 *
 * <p>위험도 축 하나로는 이 구분을 표현할 수 없다. "친구가 죽고싶다고 해서 걱정돼요"는
 * 위험 주제이므로 모델이 보수적으로 {@code MEDIUM} 이상을 주지만, 그 값이 강등된 위기
 * 후보의 해제 조건({@code CLEAR_LOW|LOW})을 통과하지 못해 3인칭 걱정 발화가 전부 위기
 * 플로우로 확정됐다. 전체 경로 평가에서 정상 61건 중 9건이 이 경로였다.
 *
 * <p>그래서 정책이 실제로 필요한 질문을 Judge 에게 직접 묻는다 — "이 위기 어휘가 화자
 * 자신의 현재 위기인가".
 */
public enum CrisisAttribution {
    /** 화자 자신의 현재 자살·자해 생각이나 충동. */
    SELF_CURRENT,
    /** 화자 자신의 과거 경험 — 회복했거나 더 이상 행동하지 않는 상태로 서술됨. */
    SELF_PAST,
    /** 타인의 위기 — 걱정·상담 요청 맥락. */
    THIRD_PARTY,
    /** 인용·미디어·학습 자료 등 서술 대상으로서의 위기 표현. */
    QUOTED,
    /** 위기 어휘가 화자의 위기를 나타내지 않음 (부정문, 관용구 등). */
    NONE
}
