package com.mio.ai.memory.retrieval;

/**
 * 메모리 컨텍스트 조립 결과의 상태 (이슈 #364, 로드맵 §12 P0-2 · §10.1).
 *
 * <p>이 값이 없으면 <b>"관련 기억이 없다"</b> 와 <b>"기억을 가져오지 못했다"</b> 가 같은
 * 빈 컨텍스트로 합쳐진다. 앞은 정상이고 뒤는 장애인데, 둘 다 조용히 기억 없는 턴을
 * 생성하므로 사후에 구별할 방법이 사라진다.
 */
public enum MemoryContextStatus {

    /** 계획한 모든 소스가 응답했다. 결과가 비어 있어도 그것은 정상적인 "기억 없음" 이다. */
    OK,

    /** 일부 소스가 실패했다. 남은 소스로 컨텍스트를 만들었으므로 턴은 완주한다. */
    PARTIAL,

    /** 컨텍스트 조립 자체가 실패했다. 이 턴에는 사용할 수 있는 기억이 없다. */
    FAILED
}
