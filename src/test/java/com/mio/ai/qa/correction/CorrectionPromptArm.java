package com.mio.ai.qa.correction;

/**
 * 정정 대응 프롬프트의 A/B 팔 (이슈 #551).
 *
 * <p>후보 문구를 <b>프로덕션 {@code PromptBuilder} 를 고치지 않고</b> 시스템 프롬프트 뒤에 붙여
 * 잰다 — 기준선(현재 프롬프트)과 후보를 같은 코드 경로에서 나란히 비교하기 위해서다. 문구가
 * 확정되면 {@link #CORRECTION_BLOCK} 을 {@code PromptBuilder} 로 옮기고, 그 뒤로는 기준선 팔이
 * 새 프로덕션과 같아지므로 이 팔은 회귀 비교용으로만 남는다.
 */
public enum CorrectionPromptArm {

    /** 현재 프로덕션 프롬프트 그대로. 수정 전 기준선이다. */
    BASELINE,

    /** 현재 프롬프트 + 정정 대응 공통 규칙. */
    WITH_CORRECTION_BLOCK;

    /**
     * 정정 대응 공통 규칙 (미오 기준). 튜닝용 세트로 반복 개선하는 대상이며, 확정되면 {@code PromptBuilder} 로
     * 옮긴다(이슈 #558). 종류별 추가 규칙은 넣지 않는다 — 측정 후에 얹기로 했다.
     *
     * <p>v6 (2026-10-07) 변경 — v4·v5(공감·감정 추측까지 막으려 한 시도)를 v3로 되돌렸다. 기준표를
     * v7(인정·재진술 외엔 "조언 또는 질문"만 위반, 공감·감정 추측은 허용)로 고친 뒤 세 버전을 전부
     * 재채점해 비교한 결과(각 run 재채점: v2→{@code 21676c1f}, v3→{@code 77ecfb7c}, v5→{@code e0208cda}),
     * <b>v3가 v5보다 더 좋았다</b> — NORMAL 91.7% vs 86.8%, SUPPORTIVE 88.3% vs 86.5%. v4·v5가 추가한
     * "구체적 나쁜 예" 문구들은 효과가 없었을 뿐 아니라(v6 기준에서도 이미 그랬다) 오히려 손해였다 —
     * 나쁜 예로 보여준 문구를 모델이 일부 따라 하는 역효과로 보인다. 그래서 v3 문구를 최종 후보로 되돌린다.
     *
     * <p>v4, v5 (2026-10-07, 폐기됨) — v3를 측정하니(run {@code b54c7953}) NORMAL 79.2%까지 올랐는데
     * SUPPORTIVE는 66.7%로 낮았다. {@code PromptBuilder}의 {@code SUPPORTIVE_INSTRUCTION}("감정을 충분히
     * 공감하라")과 충돌한다고 보고 v4에서 우선순위 문장을 추가했으나 효과 없었고(66.7%→66.7%), v5에서
     * 실제 위반 응답의 "감정 추측·증폭" 패턴을 나쁜 예로 추가했지만 그마저도 역효과였다(위 v6 참고).
     *
     * <p>v3 (2026-10-07) 변경 — 기준표 v6(인정·재진술 외 부가 내용은 전부 위반)로 재채점한 결과, v2 문구의
     * 실제 준수율이 NORMAL 45.0%·SUPPORTIVE 30.0%에 불과했다(세트 {@code correction-dev-v1}, gpt-4o, 384
     * 표본, run {@code b9fca25e}). 위반의 94%(133/142)가 "격려·의미 부여" 한 문장을 셋째 문장으로 덧붙이는
     * 것이었다 — 예: "쉴 시간이 아예 없으신 거군요. 퇴근 후에도 계속 바쁘시니 정말 힘드실 것 같아요." 금지
     * 목록을 나열하는 방식이 이 충동(대화를 자연스럽게 이어가려는 모델의 기본 습성)을 못 이긴다고 보고,
     * <b>정확히 두 문장이라는 구조적 상한</b>을 걸고, 실측된 위반 예문을 나쁜 예로 그대로 넣었다.
     *
     * <p>v2 (2026-09-21): 정정이 아닌 턴에는 적용하지 않는다는 범위 문장, "그렇군요"만으로 끝내지 않기,
     * 상황에 맞춘 제안 포함 조언 금지, 질문 금지를 추가했다 (파일럿에서 드러난 미탐·질문 잔존에 대응).
     */
    static final String CORRECTION_BLOCK = """
            [정정 대응]
            먼저 판단하세요. 사용자가 당신의 직전 말을 바로잡거나, 반박하거나, 제안을 거절하거나, 같은 내용을
            다시 설명하고 있나요?
            - 아니라면: 이 지시를 적용하지 말고 평소처럼 답하세요. 사용자가 바로잡지 않았는데 "제가 잘못
              짚었네요" 같은 사과나 인정을 하지 마세요.
            - 맞다면: 응답은 반드시 정확히 두 문장으로만 쓰세요. 세 번째 문장을 쓰고 싶은 충동이 들면 그게
              바로 금지된 덧붙이기이니, 쓰지 말고 두 번째 문장의 마침표에서 멈추세요.
              1. 첫 문장: 바로잡힌 내용을 짚어서 인정하세요 ("~가 아니었군요"). "그렇군요"만으로 끝내지
                 마세요.
              2. 둘째 문장: 사용자가 말한 내용을 당신의 말로 다시 정리하세요. 사용자가 말하지 않은 사정이나
                 원인을 덧붙이지 마세요.
              셋째 문장은 쓰지 마세요. 공감·위로("정말 힘드실 것 같아요", "고생 많으셨어요"), 의미 부여,
              조언이나 제안(일반 팁이든 상황에 맞춘 제안이든), 질문, "~하시면 좋겠어요"/"~않으셨으면
              해요"/"~도움이 될 수 있어요"/"~해 보세요"/"~중요해요" 같은 마무리는 전부 셋째 문장에
              해당합니다. 직전에 한 조언도 반복하지 마세요.

              나쁜 예(실제 위반 사례): "쉴 시간이 아예 없으신 거군요. 퇴근 후에도 계속 바쁘시니 정말
              힘드실 것 같아요." — 둘째 문장까지는 맞지만 셋째 문장에 공감을 덧붙여 규칙을 어겼습니다.
              좋은 예(같은 상황, 두 문장으로 끝남): "쉴 시간이 아예 없으신 거군요. 퇴근 후에도 쉴 틈이
              없으셨다는 거네요."
            """;

    /** 후보 블록 문구의 지문(sha-256 앞 8자). 블록을 고쳐 가며 잰 결과가 어느 문구의 것인지 가리는 데 쓴다. */
    static String blockFingerprint() {
        try {
            byte[] digest = java.security.MessageDigest.getInstance("SHA-256")
                    .digest(CORRECTION_BLOCK.getBytes(java.nio.charset.StandardCharsets.UTF_8));
            return java.util.HexFormat.of().formatHex(digest).substring(0, 8);
        } catch (java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    public String apply(String systemPrompt) {
        return this == BASELINE ? systemPrompt : systemPrompt + "\n\n" + CORRECTION_BLOCK;
    }
}
